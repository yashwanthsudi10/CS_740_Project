function [summary, eigenModel, fisherModel] = evaluate_face_experiment( ...
    datasetName, trainPerSubject, Xtrain, trainLabels, Xtest, testLabels)


numClasses = numel(unique(trainLabels));
numTrain = size(Xtrain, 2);
maxPca = min(numTrain - numClasses, size(Xtrain, 2) - 1);
maxFisher = min(numClasses - 1, maxPca);

timer = tic;
eigenModel = train_eigenfaces(Xtrain, maxPca);
eigenTrainingSeconds = toc(timer);

timer = tic;
fisherModel = train_fisherfaces(Xtrain, trainLabels);
fisherTrainingSeconds = toc(timer);

[eigenEuclideanAccuracy, eigenEuclideanSeconds] = ...
    local_accuracy(eigenModel, Xtrain, trainLabels, Xtest, testLabels, ...
    maxPca, 'euclidean');
[eigenCorrelationAccuracy, eigenCorrelationSeconds] = ...
    local_accuracy(eigenModel, Xtrain, trainLabels, Xtest, testLabels, ...
    maxPca, 'correlation');
[fisherEuclideanAccuracy, fisherEuclideanSeconds] = ...
    local_accuracy(fisherModel, Xtrain, trainLabels, Xtest, testLabels, ...
    maxFisher, 'euclidean');
[fisherCorrelationAccuracy, fisherCorrelationSeconds] = ...
    local_accuracy(fisherModel, Xtrain, trainLabels, Xtest, testLabels, ...
    maxFisher, 'correlation');

summary = table( ...
    repmat(string(datasetName), 4, 1), ...
    repmat(trainPerSubject, 4, 1), ...
    repmat(size(Xtrain, 2), 4, 1), ...
    repmat(size(Xtest, 2), 4, 1), ...
    ["Eigenfaces"; "Eigenfaces"; "Fisherfaces"; "Fisherfaces"], ...
    ["Euclidean"; "Correlation"; "Euclidean"; "Correlation"], ...
    [maxPca; maxPca; maxFisher; maxFisher], ...
    [eigenEuclideanAccuracy; eigenCorrelationAccuracy; ...
     fisherEuclideanAccuracy; fisherCorrelationAccuracy], ...
    [100 - eigenEuclideanAccuracy; 100 - eigenCorrelationAccuracy; ...
     100 - fisherEuclideanAccuracy; 100 - fisherCorrelationAccuracy], ...
    [eigenTrainingSeconds; eigenTrainingSeconds; ...
     fisherTrainingSeconds; fisherTrainingSeconds], ...
    [eigenEuclideanSeconds; eigenCorrelationSeconds; ...
     fisherEuclideanSeconds; fisherCorrelationSeconds], ...
    [NaN; NaN; fisherModel.ldaSeparationRatio; fisherModel.ldaSeparationRatio], ...
    'VariableNames', {'Dataset', 'TrainPerSubject', 'TrainingFaces', ...
    'TestFaces', 'Method', 'Metric', 'Dimensions', 'AccuracyPercent', ...
    'ErrorPercent', 'TrainingSeconds', 'RecognitionSeconds', ...
    'LDASeparationRatio'});
end

function [accuracy, seconds] = local_accuracy(model, Xtrain, trainLabels, ...
    Xtest, testLabels, dimensions, metric)
timer = tic;
predicted = predict_nearest_neighbor(model, Xtrain, trainLabels, ...
    Xtest, dimensions, metric);
seconds = toc(timer);
accuracy = 100 * mean(predicted == testLabels);
end
